#!/usr/bin/env node
/* Encrypts verify/records.json (gitignored) into public/verify/records.dat
   and regenerates public/verify/key.js (the AES-256-GCM key, hex).

   Run: node scripts/encrypt-records.mjs
   The key ships to the browser on purpose: it protects the repo from
   casual scraping, NOT site visitors. Real protection needs a server-side
   verifier (e.g. a Cloudflare Worker). Keep the key in sync by always
   running this script after editing verify/records.json. */

import {readFile, writeFile} from "node:fs/promises";
import path from "node:path";
import {fileURLToPath} from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
await import(new URL("../public/verify/records-lib.js", import.meta.url).href);
const V = globalThis.NatdsVerify;
const KEY = "ee31a52e7c15f07fa4eb1d1ae86a6faa1e64c335dea1abe2e9aef1f93a759f1d";

const src = JSON.parse(await readFile(path.join(root, "verify/records.json"), "utf8"));
const records = src.records || [];

if (records.length === 0) throw new Error("verify/records.json has no records");

const seen = new Set();
for (const r of records) {
  if (!r.id || !V.isValidFormat(r.id)) throw new Error(`Bad certificate ID format: ${r.id}`);
  if (seen.has(r.id)) throw new Error(`Duplicate certificate ID: ${r.id}`);
  seen.add(r.id);
  if (!r.name || !r.programme || !r.date) throw new Error(`Record ${r.id} missing name/programme/date`);
}

const dat = await V.encryptRecords({version: 1, records}, KEY);

const roundtrip = await V.decryptRecords(dat, KEY);
if (roundtrip.records.length !== records.length) throw new Error("Round-trip decrypt failed");

await writeFile(path.join(root, "public/verify/records.dat"), JSON.stringify(dat) + "\n");
await writeFile(
  path.join(root, "public/verify/key.js"),
  `/* Generated by scripts/encrypt-records.mjs — do not edit by hand. */\nwindow.NATDS_VERIFY_KEY=${JSON.stringify(KEY)};\n`
);

console.log(`Encrypted ${records.length} records -> public/verify/records.dat (+ key.js)`);
